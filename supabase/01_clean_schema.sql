-- ==============================================================================
-- يشمل:
-- 1. جدول الحسابات والملفات الشخصية للباحثين (Profiles)
-- 2. جدول المشاريع البحثية (Research Projects)
-- 3. جدول التظليلات والملاحظات الأكاديمية (Annotations)
-- 4. جدول الكيانات المستخرجة بالذكاء الاصطناعي (Detected Entities)
-- 5. جدول الجذور والتحليل الصرفي الثلاثي (Word Roots)
-- 6. الفهارس المتقدمة لتسريع البحث (Performance Indexes)
-- 7. قواعد الأمان وسياسات الوصول (Row Level Security - RLS)
-- ==============================================================================

-- تفعيل الملحقات الضرورية
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pg_trgm";

-- ------------------------------------------------------------------------------
-- 1. جدول الملفات الشخصية للباحثين (Profiles)
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    email TEXT,
    full_name TEXT DEFAULT 'باحث أكاديمي',
    academic_field TEXT DEFAULT 'دراسات عامة', -- تاريخ، أدب عربي، لسانيات، شريعة، إلخ.
    avatar_url TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- ------------------------------------------------------------------------------
-- 2. جدول المشاريع البحثية (Research Projects)
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.research_projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    description TEXT,
    color VARCHAR(32) DEFAULT '#4F46E5',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- ------------------------------------------------------------------------------
-- 3. جدول التظليلات والملاحظات (Annotations)
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.annotations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    author_name VARCHAR(255) DEFAULT 'باحث',
    project_id BIGINT REFERENCES public.research_projects(id) ON DELETE SET NULL,
    url TEXT NOT NULL,
    page_title TEXT,
    selected_text TEXT NOT NULL,
    note TEXT,
    color VARCHAR(32) DEFAULT '#FFE082',
    visibility VARCHAR(32) DEFAULT 'private', -- 'private' أو 'public'
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- ------------------------------------------------------------------------------
-- 4. جدول الكيانات المستخرجة بالذكاء الاصطناعي (Detected Entities)
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.detected_entities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    annotation_id BIGINT NOT NULL REFERENCES public.annotations(id) ON DELETE CASCADE,
    text TEXT NOT NULL,
    category VARCHAR(128) NOT NULL, -- PERSON, LOCATION, CONCEPT, DATE, EVENT, etc.
    confidence REAL DEFAULT 1.0,
    source VARCHAR(64) DEFAULT 'Hybrid', -- Hybrid, BERT, Groq LLM, Rule
    start_char INT DEFAULT 0,
    end_char INT DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ------------------------------------------------------------------------------
-- 5. جدول الجذور والتحليل الصرفي الثلاثي (Word Roots)
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.word_roots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id BIGINT NOT NULL REFERENCES public.detected_entities(id) ON DELETE CASCADE,
    word VARCHAR(128) NOT NULL,
    root VARCHAR(64),
    lemma VARCHAR(128),
    pos VARCHAR(64),
    segmentation VARCHAR(128),
    source VARCHAR(64) DEFAULT 'camel_tools',
    status VARCHAR(32) DEFAULT 'analyzed',
    is_trilateral BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ==============================================================================
-- 6. فهارس تسريع الأداء والبحث (Performance Indexes)
-- ==============================================================================
CREATE INDEX IF NOT EXISTS idx_annotations_url ON public.annotations(url);
CREATE INDEX IF NOT EXISTS idx_annotations_user_id ON public.annotations(user_id);
CREATE INDEX IF NOT EXISTS idx_annotations_project_id ON public.annotations(project_id);
CREATE INDEX IF NOT EXISTS idx_annotations_created_at ON public.annotations(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_annotations_text_trgm ON public.annotations USING gin (selected_text gin_trgm_ops);

CREATE INDEX IF NOT EXISTS idx_entities_annotation_id ON public.detected_entities(annotation_id);
CREATE INDEX IF NOT EXISTS idx_entities_category ON public.detected_entities(category);
CREATE INDEX IF NOT EXISTS idx_entities_text ON public.detected_entities(text);

CREATE INDEX IF NOT EXISTS idx_roots_entity_id ON public.word_roots(entity_id);
CREATE INDEX IF NOT EXISTS idx_roots_root ON public.word_roots(root);
CREATE INDEX IF NOT EXISTS idx_roots_lemma ON public.word_roots(lemma);

-- ==============================================================================
-- 7. دوال التحديث التلقائي لوقت التعديل (Updated At Trigger)
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.set_current_timestamp_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_annotations_updated_at ON public.annotations;
CREATE TRIGGER trigger_annotations_updated_at
BEFORE UPDATE ON public.annotations
FOR EACH ROW
EXECUTE FUNCTION public.set_current_timestamp_updated_at();

DROP TRIGGER IF EXISTS trigger_profiles_updated_at ON public.profiles;
CREATE TRIGGER trigger_profiles_updated_at
BEFORE UPDATE ON public.profiles
FOR EACH ROW
EXECUTE FUNCTION public.set_current_timestamp_updated_at();

-- ==============================================================================
-- 8. ربط إنشاء الحسابات بإنشاء ملف شخصي تلقائياً (Auth Profile Trigger)
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO public.profiles (id, email, full_name)
    VALUES (
        NEW.id,
        NEW.email,
        COALESCE(NEW.raw_user_meta_data->>'full_name', 'باحث أكاديمي')
    )
    ON CONFLICT (id) DO NOTHING;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
AFTER INSERT ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- ==============================================================================
-- 9. سياسات الأمان والحماية (Row Level Security - RLS)
-- ==============================================================================
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.research_projects ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.annotations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.detected_entities ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.word_roots ENABLE ROW LEVEL SECURITY;

-- السماح بالوصول الكامل أثناء التطوير والاختبار التجريبي (Dev / Anon / Authenticated)
-- حتى لا يتعطل حفظ الإضافة أو الـ API في مرحلة الاختبار والتسليم للدكتور:
CREATE POLICY "Allow public read on annotations" ON public.annotations FOR SELECT USING (true);
CREATE POLICY "Allow public insert on annotations" ON public.annotations FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public update on annotations" ON public.annotations FOR UPDATE USING (true);
CREATE POLICY "Allow public delete on annotations" ON public.annotations FOR DELETE USING (true);

CREATE POLICY "Allow public read on entities" ON public.detected_entities FOR SELECT USING (true);
CREATE POLICY "Allow public insert on entities" ON public.detected_entities FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public update on entities" ON public.detected_entities FOR UPDATE USING (true);
CREATE POLICY "Allow public delete on entities" ON public.detected_entities FOR DELETE USING (true);

CREATE POLICY "Allow public read on roots" ON public.word_roots FOR SELECT USING (true);
CREATE POLICY "Allow public insert on roots" ON public.word_roots FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public update on roots" ON public.word_roots FOR UPDATE USING (true);
CREATE POLICY "Allow public delete on roots" ON public.word_roots FOR DELETE USING (true);

CREATE POLICY "Allow public access on projects" ON public.research_projects FOR ALL USING (true);
CREATE POLICY "Allow users to read profiles" ON public.profiles FOR SELECT USING (true);
CREATE POLICY "Allow users to update own profile" ON public.profiles FOR UPDATE USING (auth.uid() = id);

-- ==============================================================================
-- 10. منح الصلاحيات البرمجية للأدوار (Grants for anon, authenticated, service_role)
-- ==============================================================================
GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON ALL TABLES IN SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON ALL ROUTINES IN SCHEMA public TO anon, authenticated, service_role;

ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO anon, authenticated, service_role;
