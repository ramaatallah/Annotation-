-- 001_core.sql
-- Core database tables for Arabic Academic Annotation & Morphological Knowledge Base

create extension if not exists pg_trgm;

-- Pages annotated by users
create table if not exists public.pages (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users on delete cascade,
  url text not null,
  normalized_url text not null,
  title text default '',
  domain text,
  created_at timestamptz default now(),
  unique (user_id, normalized_url)
);
create index if not exists idx_pages_user_url on public.pages (user_id, normalized_url);

-- User annotations with idempotency id generated by client
create table if not exists public.annotations (
  id uuid primary key,
  user_id uuid not null references auth.users on delete cascade,
  page_id uuid not null references public.pages on delete cascade,
  selected_text text not null,
  note text default '',
  context_before text default '',
  context_after text default '',
  anchor_data jsonb default '{}'::jsonb,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);
create index if not exists idx_annotations_user_page on public.annotations (user_id, page_id);

-- Tracking analysis runs for reproducibility (stores hash & versions, not text)
create table if not exists public.analysis_runs (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users on delete cascade,
  text_hash text not null,
  versions jsonb not null,
  latency_ms int,
  degraded boolean default false,
  created_at timestamptz default now()
);

-- Shared Knowledge Base Entities (Shared read-only for authenticated researchers, written by backend service role)
create table if not exists public.kb_entities (
  id uuid primary key default gen_random_uuid(),
  entity_text text not null,
  normalized_text text not null,
  entity_type text not null,
  entity_type_ar text,
  subtype_ar text,
  domain text,
  created_at timestamptz default now(),
  unique (normalized_text, entity_type)
);
-- If kb_entities already existed from previous version, add missing columns
alter table public.kb_entities add column if not exists domain text;
alter table public.kb_entities add column if not exists subtype_ar text;
alter table public.kb_entities add column if not exists entity_type_ar text;
alter table public.kb_entities add column if not exists normalized_text text;

create index if not exists kb_norm_trgm on public.kb_entities using gin (normalized_text gin_trgm_ops);

-- Word-level root representations for multi-word entities
create table if not exists public.entity_words (
  entity_id uuid not null references public.kb_entities on delete cascade,
  position smallint not null,
  word text not null,
  root text,
  root_len smallint,
  root_status text not null check (root_status in
    ('found','quadrilateral','proper_noun','foreign','ambiguous','stopword','not_applicable','unknown')),
  root_engine text,
  engine_version text,
  candidates jsonb,
  needs_review boolean not null default false,
  primary key (entity_id, position)
);
create index if not exists idx_entity_words_root on public.entity_words (root) where root is not null;

-- Link between Annotations and KB Entities
create table if not exists public.annotation_entities (
  id uuid primary key default gen_random_uuid(),
  annotation_id uuid not null references public.annotations on delete cascade,
  entity_id uuid not null references public.kb_entities,
  user_id uuid not null references auth.users on delete cascade,
  start_offset int,
  end_offset int,
  source text not null check (source in ('bert','llm','both')),
  bert_score real,
  llm_self_confidence real,
  conflict boolean default false,
  user_verified boolean default false,
  words_snapshot jsonb,
  run_id uuid references public.analysis_runs,
  created_at timestamptz default now(),
  unique (annotation_id, entity_id, start_offset)
);
-- If annotation_entities already existed from previous version, add missing columns
alter table public.annotation_entities add column if not exists words_snapshot jsonb;
alter table public.annotation_entities add column if not exists run_id uuid references public.analysis_runs;
alter table public.annotation_entities add column if not exists conflict boolean default false;
alter table public.annotation_entities add column if not exists bert_score real;
alter table public.annotation_entities add column if not exists llm_self_confidence real;
create index if not exists idx_annotation_entities_ann on public.annotation_entities (annotation_id);

-- Researcher feedback and corrections for continuous quality improvement
create table if not exists public.entity_corrections (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users on delete cascade,
  annotation_entity_id uuid references public.annotation_entities on delete set null,
  field text not null check (field in ('type','span','root','delete')),
  old_value text,
  new_value text,
  status text not null default 'pending',
  created_at timestamptz default now()
);

-- Per-user API usage quotas
create table if not exists public.api_usage (
  user_id uuid not null,
  day date not null,
  calls int not null default 0,
  primary key (user_id, day)
);
